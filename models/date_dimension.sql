WITH CTE AS (
SELECT 
TO_TIMESTAMP(STARTED_AT) AS STARTED_AT,
DATE (TO_TIMESTAMP(STARTED_AT)) AS DATE_STARTED_AT,
HOUR (TO_TIMESTAMP(STARTED_AT)) AS HR_STARTED_AT,
CASE WHEN DAYNAME(TO_TIMESTAMP(STARTED_AT)) IN ('Sat', 'Sun') 
   THEN 'WEEKEND'
   ELSE 'BUSINESSDAY'
END AS WEEK,
CASE WHEN MONTH (TO_TIMESTAMP(STARTED_AT)) IN (1,2,3)
     THEN 'Q1'
     WHEN MONTH (TO_TIMESTAMP(STARTED_AT)) IN (4,5,6)
     THEN 'Q2'
     WHEN MONTH (TO_TIMESTAMP(STARTED_AT)) IN (7,8,9)
     THEN 'Q3'
     ELSE 'Q4'
END AS QUATER,
TO_TIMESTAMP(ENDED_AT) AS ENDED_AT
FROM
{{ source('dbtdemo', 'bike') }}
)

SELECT * FROM CTE